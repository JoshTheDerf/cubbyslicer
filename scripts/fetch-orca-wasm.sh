#!/usr/bin/env bash
# Stage the OrcaSlicer WASM engine into public/wasm/orca/ (not committed).
#
# Source (first match wins):
#   $ORCA_WASM_BUILD            explicit build dir
#   ../slicers/orcaslicer-wasm/build-wasm   (local build; see that repo's scripts/build-wasm.sh)
#
# Multi-threaded build (optional; used when the page is cross-origin isolated):
#   $ORCA_WASM_BUILD_MT         explicit build dir
#   ../slicers/orcaslicer-wasm/build-wasm-mt  (WASM_THREADS=1 bash scripts/build-wasm.sh)
#   ORCA_SKIP_MT=1              stage the single-threaded build only (removes mt/)
#
# Staged:
#   slicer.mjs slicer.wasm slicer.data   engine (ABI: docs/ENGINE-CONTRACT.md)
#   mt/slicer.{mjs,wasm,data}            pthreads engine (same version + ABI, checked)
#   schema.json version.json             generated by scripts/gen-schema.mjs
#   profiles/                            Orca vendor profile tree + _index.json
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PORT="$REPO_ROOT/../slicers/orcaslicer-wasm"
BUILD="${ORCA_WASM_BUILD:-$PORT/build-wasm}"
BUILD_MT="${ORCA_WASM_BUILD_MT:-$PORT/build-wasm-mt}"
PROFILES_SRC="${ORCA_PROFILES_SRC:-$PORT/orca/resources/profiles}"
DEST="$REPO_ROOT/public/wasm/orca"

for f in slicer.mjs slicer.wasm schema.json version.json; do
  [[ -f "$BUILD/$f" ]] || { echo "error: $BUILD/$f missing (build the engine + run gen-schema.mjs)" >&2; exit 1; }
done

mkdir -p "$DEST"
rm -f "$DEST/slicer.js"   # pre-ABI-v1 artifact
for f in slicer.mjs slicer.wasm schema.json version.json; do cp -f "$BUILD/$f" "$DEST/$f"; done
if [[ -f "$BUILD/slicer.data" ]]; then cp -f "$BUILD/slicer.data" "$DEST/"; else rm -f "$DEST/slicer.data"; fi

# Multi-threaded engine → mt/. It must be the same engine version + bridge ABI
# as the single-threaded one (schema.json / profiles are shared).
rm -rf "${DEST:?}/mt"
if [[ "${ORCA_SKIP_MT:-0}" != "1" ]]; then
  if [[ -f "$BUILD_MT/slicer.mjs" && -f "$BUILD_MT/slicer.wasm" && -f "$BUILD_MT/version.json" ]]; then
    python3 -c '
import json, sys
st, mt = (json.load(open(p)) for p in sys.argv[1:3])
keys = ("engine", "version", "bridge")
if any(st.get(k) != mt.get(k) for k in keys):
    sys.exit(f"error: MT build {[mt.get(k) for k in keys]} != ST build {[st.get(k) for k in keys]}; rebuild both")
' "$BUILD/version.json" "$BUILD_MT/version.json"
    mkdir -p "$DEST/mt"
    for f in slicer.mjs slicer.wasm; do cp -f "$BUILD_MT/$f" "$DEST/mt/$f"; done
    if [[ -f "$BUILD_MT/slicer.data" ]]; then cp -f "$BUILD_MT/slicer.data" "$DEST/mt/"; fi
    echo "mt: staged $(du -sh "$DEST/mt" | cut -f1) from $BUILD_MT"
  else
    echo "warning: no multi-threaded build at $BUILD_MT (single-threaded only)" >&2
  fi
fi

if [[ "${ORCA_SKIP_PROFILES:-0}" != "1" ]]; then
  [[ -d "$PROFILES_SRC" ]] || { echo "error: profiles missing at $PROFILES_SRC" >&2; exit 1; }
  rm -rf "$DEST/profiles"
  mkdir -p "$DEST/profiles"
  cp -R "$PROFILES_SRC/." "$DEST/profiles/"
  # Browsers can't list directories: write the vendor index the catalog reads.
  python3 - "$DEST/profiles" <<'PY'
import json, os, sys
dest = sys.argv[1]
ids = sorted(n[:-5] for n in os.listdir(dest)
             if n.endswith('.json') and n != '_index.json' and os.path.isdir(os.path.join(dest, n[:-5])))
json.dump(ids, open(os.path.join(dest, '_index.json'), 'w'))
print(f'profiles: {len(ids)} vendors')
PY
  # One-request-per-vendor bundles (catalog falls back to single files).
  node "$REPO_ROOT/scripts/dev/build-profile-bundles.mjs" "$DEST/profiles"
fi
echo "Staged $(python3 -c "import json;print(json.load(open('$DEST/version.json'))['version'])") into $DEST"
