/** Orca 2.5 host changes: UltiMaker, Moonraker print_started / print_queued, Qidi Box slots, lane_data sync. */
import { describe, expect, it } from 'vitest';
import { parseLaneData, laneColour, matchLane, type FilamentCandidate } from './filamentSync';
import { fetchLaneData, isQidi, moonraker, qidiToolSlotScript } from './hosts/moonraker';
import { estimatedSeconds, griffinCompatible, requestUltimakerCredentials, ultimaker } from './hosts/ultimaker';
import { ctx, fakeEnv, gcode } from './testing';

const form = (b: unknown) => b as FormData;
const job = (over: Partial<{ print: boolean; folder: string; filename: string; file: Blob; slotMapping: number[] }> = {}) =>
  ({ file: gcode(), filename: 'cube.gcode', folder: '', print: false, ...over });

describe('Moonraker 2.5', () => {
  it('asks Moonraker to start the print and trusts print_started / print_queued (bare reply)', async () => {
    const { env, calls } = fakeEnv(() => ({ status: 201, body: { item: { path: 'cube.gcode' }, print_started: false, print_queued: true } }));
    const r = await moonraker.upload(ctx(), job({ print: true }), env);
    expect(form(calls[0].body).get('print')).toBe('true');
    expect(calls).toHaveLength(1);
    expect(r).toMatchObject({ printed: true, message: expect.stringMatching(/queued/) });
  });
  it('falls back to printer/print/start when neither flag is set', async () => {
    const { env, calls } = fakeEnv((r) => (r.url.endsWith('upload') ? { status: 201, body: { item: { path: 'a/cube-1.gcode' } } } : { body: { result: 'ok' } }));
    await moonraker.upload(ctx(), job({ print: true }), env);
    expect(JSON.parse(calls[1].body as string)).toEqual({ filename: 'a/cube-1.gcode' });
  });
  it('Qidi Box: saves the slot per filament, then starts the print itself', async () => {
    const { env, calls } = fakeEnv((r) => (r.url.endsWith('upload') ? { status: 201, body: { item: { path: 'cube.gcode' } } } : { body: { result: 'ok' } }));
    await moonraker.upload(ctx(), job({ print: true, slotMapping: [2, -1, 15] }), env);
    expect(form(calls[0].body).get('print')).toBe('false');
    expect(calls[1].url).toBe('http://192.168.1.5/printer/gcode/script');
    expect(JSON.parse(calls[1].body as string).script).toBe(`SAVE_VARIABLE VARIABLE=value_t0 VALUE="'slot2'"\nSAVE_VARIABLE VARIABLE=value_t2 VALUE="'slot15'"`);
    expect(calls[2].url).toBe('http://192.168.1.5/printer/print/start');
    expect(qidiToolSlotScript([16, -2, 1.5])).toBe('');
    expect(isQidi('Qidi X-Max 4')).toBe(true);
  });
  it('reads lane_data (404 = none) and maps lanes like the Moonraker agent', async () => {
    const lanes = {
      result: { namespace: 'lane_data', value: {
        lane1: { lane: '0', color: '0xff0000', material: 'PLA', filament_id: 'OFabc', nozzle_temp: 210, bed_temp: 60 },
        lane2: { lane: '1', color: '#00FF0080', material: 'petg', filament_id: 42 },
        lane3: { lane: '', material: 'ABS' },
      } },
    };
    const { env } = fakeEnv(() => ({ body: lanes }));
    const parsed = parseLaneData(await fetchLaneData(ctx(), env));
    expect(parsed).toEqual([
      { index: 0, colour: '#FF0000', material: 'PLA', filamentId: 'OFabc', nozzleTemp: 210, bedTemp: 60 },
      { index: 1, colour: '#00FF0080', material: 'petg', filamentId: '', nozzleTemp: 0, bedTemp: 0 },
    ]);
    expect(laneColour('zz')).toBe('');
    const { env: none } = fakeEnv(() => undefined);
    expect(await fetchLaneData(ctx(), none)).toBeNull();
    const c: FilamentCandidate[] = [
      { id: 'a', name: 'Bambu PLA Basic @BBL', filamentType: 'PLA', system: true, filamentId: 'OFabc' },
      { id: 'b', name: 'Generic PETG @System', filamentType: 'PETG', system: true },
      { id: 'c', name: 'Generic PLA @System', filamentType: 'PLA', system: true },
    ];
    expect(matchLane(parsed[0], c)?.id).toBe('a');
    expect(matchLane({ ...parsed[0], filamentId: 'nope' }, c)?.id).toBe('c');
    expect(matchLane(parsed[1], c)?.id).toBe('b');
  });
});

describe('UltiMaker', () => {
  const header = ';START_OF_HEADER\n;HEADER_VERSION:0.1\n; generated by OrcaSlicer 2.5.0 on 2026-01-02 at 10:11:12\n;PRINT.TIME:0\n;END_OF_HEADER\nG28\n; estimated printing time (normal mode) = 1h 2m 3s\n';
  it('makes the G-code Griffin-safe', () => {
    expect(estimatedSeconds(header)).toBe(3723);
    expect(estimatedSeconds('; estimated printing time (normal mode) = 1d 0h 0m 5s')).toBe(86405);
    const out = griffinCompatible(`junk\n${header}`);
    expect(out.startsWith(';START_OF_HEADER')).toBe(true);
    expect(out).toContain('; generated by OrcaSlicer 2.5.0 on 2026-01-02 at 10-11-12');
    expect(out).toContain(';PRINT.TIME:3723');
    expect(griffinCompatible('G28\n')).toBe('G28\n');
  });
  it('tests the variant, then the credentials (waiting / authorized)', async () => {
    const route = (status: string) => fakeEnv((r) => {
      if (r.url.endsWith('system/variant')) return { body: '"Ultimaker S5"' };
      if (r.url.includes('auth/check/')) return { body: { message: status } };
      if (r.url.endsWith('auth/verify')) return { body: { message: 'ok' } };
      return undefined;
    });
    const ok = route('authorized');
    expect(await ultimaker.test(ctx({ user: 'id1', password: 'k' }), ok.env)).toMatchObject({ detail: 'Ultimaker S5' });
    expect(ok.calls[1].url).toBe('http://192.168.1.5/api/v1/auth/check/id1');
    await expect(ultimaker.test(ctx({ user: 'id1', password: 'k' }), route('unknown').env)).rejects.toThrow(/waiting for approval/);
    await expect(ultimaker.test(ctx(), route('authorized').env)).rejects.toThrow(/No authentication credentials/);
    const { env } = fakeEnv(() => ({ body: '"Ultimaker 2+"' }));
    await expect(ultimaker.test(ctx({ user: 'a', password: 'b' }), env)).rejects.toThrow(/UltiMaker 3 \/ S5/);
  });
  it('requests credentials and uploads a print job with digest auth', async () => {
    const { env: e1, calls: c1 } = fakeEnv(() => ({ body: { id: 'ID', key: 'KEY' } }));
    expect(await requestUltimakerCredentials(ctx(), e1)).toEqual({ id: 'ID', key: 'KEY' });
    expect(form(c1[0].body).get('application')).toBe('CubbySlicer');
    let challenged = false;
    const { env, calls } = fakeEnv((r) => {
      if (r.url.endsWith('printer/status')) return { body: '"idle"' };
      if (r.url.endsWith('print_job')) {
        if (!r.headers?.Authorization) { challenged = true; return { status: 401, headers: { 'WWW-Authenticate': 'Digest realm="Jedi-API", nonce="n1", qop="auth"' } }; }
        return { status: 201, body: { message: 'ok' } };
      }
      return undefined;
    });
    const r = await ultimaker.upload(ctx({ user: 'ID', password: 'KEY' }), job({ print: true, file: gcode(header) }), env);
    expect(challenged).toBe(true);
    const last = calls[calls.length - 1];
    expect(last.headers?.Authorization).toMatch(/^Digest username="ID"/);
    expect(form(last.body).get('jobname')).toBe('cube.gcode');
    expect(await (form(last.body).get('file') as Blob).text()).toContain(';PRINT.TIME:3723');
    expect(r.printed).toBe(true);
    await expect(ultimaker.upload(ctx(), job(), env)).rejects.toThrow(/Upload & Print/);
  });
});

describe('Moonraker error reasons (PrintHost.cpp 2.5)', () => {
  it('takes the reason from the traceback', async () => {
    const { moonrakerErrorReason } = await import('./util');
    const tb = 'Traceback (most recent call last):\n  File "x.py", line 1\n    raise\ntornado.web.HTTPError: HTTP 400: Klippy busy (printer is printing)\n';
    expect(moonrakerErrorReason(JSON.stringify({ error: { code: 400, message: 'Klippy busy', traceback: tb } }))).toBe('Klippy busy (printer is printing)');
    const other = 'Traceback (most recent call last):\n  File "x.py", line 1\n    f()\nKeyError: \'gcodes\'\n';
    expect(moonrakerErrorReason(JSON.stringify({ error: { code: 500, message: 'Internal', traceback: other } }))).toBe("Internal (KeyError: 'gcodes')");
    expect(moonrakerErrorReason('not json')).toBe('');
  });
});
