/**
 * UltiMaker (Griffin firmware: UltiMaker 3 / S5) — Orca 2.5 UltiMaker.cpp.
 * HTTP digest with an id / key pair the printer issues and the user approves
 * on its screen.
 *   credentials: POST api/v1/auth/request  multipart application, user → { id, key }
 *   test:   GET api/v1/system/variant → "Ultimaker 3…" | "Ultimaker S5"
 *           GET api/v1/auth/check/<id> → { message: authorized | unknown (waiting) | unauthorized }
 *           GET api/v1/auth/verify (digest) → "ok"
 *   upload: GET api/v1/printer/status (reachability), then
 *           POST api/v1/print_job (digest) multipart jobname, file — the printer starts the job.
 * The G-code is made Griffin-safe first (makeGriffinCompatible).
 *
 * Orca follows the upload with a Duet-style rr_gcode M32 request whose URL
 * can't exist on Griffin (the print_job upload already starts the print);
 * that request is left out here.
 */
import { digestClient } from '../digest';
import { HostError, type HostContext, type HostEnv, type PrintHostDriver } from '../types';
import { client, expectOk, formFile, tryJson } from '../util';

const NO_CHALLENGE = 'The printer wants an HTTP digest login, but the browser can’t read its challenge (WWW-Authenticate isn’t exposed to other sites). Put the printer behind a proxy that exposes it (see Setup help).';

function um(ctx: HostContext, env: HostEnv) {
  return digestClient(client(ctx, env), ctx.user, ctx.password, 'The UltiMaker', NO_CHALLENGE);
}

/** `; estimated printing time (normal mode) = 1d 2h 3m 4s` → seconds (0 when absent). */
export function estimatedSeconds(gcode: string): number {
  const m = gcode.match(/^; estimated printing time \(normal mode\) = (.+)$/m);
  if (!m) return 0;
  const unit: Record<string, number> = { d: 86400, h: 3600, m: 60, s: 1 };
  let total = 0;
  for (const [, n, u] of m[1].matchAll(/(\d+)\s*([dhms])/g)) total += Number(n) * unit[u];
  return total;
}

/**
 * UltiMaker::makeGriffinCompatible: keep the file from `;START_OF_HEADER`,
 * replace the colons of the "generated by" timestamp (more than one colon on
 * a header line crashes the printer) and fill `;PRINT.TIME:` in seconds.
 * A file without a Griffin header is left as it is (Orca would upload an
 * empty file).
 */
export function griffinCompatible(gcode: string): string {
  const start = gcode.search(/^;START_OF_HEADER/m);
  if (start < 0) return gcode;
  const seconds = estimatedSeconds(gcode);
  return gcode.slice(start).split('\n').map((line) => {
    if (line.startsWith('; generated by ')) return line.replace(/:/g, '-');
    if (line.startsWith(';PRINT.TIME:')) return `;PRINT.TIME:${seconds}`;
    return line;
  }).join('\n');
}

/** Ask the printer for an id / key pair; the user then approves it on the printer's screen. */
export async function requestUltimakerCredentials(ctx: HostContext, env: HostEnv, application = 'CubbySlicer'): Promise<{ id: string; key: string }> {
  const c = client(ctx, env);
  const body = new FormData();
  body.append('application', application);
  body.append('user', application);
  const r = expectOk(await c.send({ method: 'POST', url: c.url('api/v1/auth/request'), body }), 'The printer didn’t issue credentials');
  const j = tryJson<{ id?: string; key?: string }>(r.text);
  if (!j?.id || !j.key) throw new HostError('protocol', `The printer returned an empty ID or key (ID=${j?.id ?? ''} KEY=${j?.key ?? ''}).`);
  return { id: j.id, key: j.key };
}

function message(text: string): string {
  const j = tryJson<{ message?: string } | string>(text);
  return typeof j === 'string' ? j : j?.message ?? text.trim();
}

/** UltiMaker::test_auth. */
async function checkAuth(ctx: HostContext, env: HostEnv, signal?: AbortSignal): Promise<void> {
  if (!ctx.user || !ctx.password) throw new HostError('config', 'No authentication credentials: use “Request credentials”, approve them on the printer, then test again.');
  const c = um(ctx, env);
  const st = message(expectOk(await c.send({ method: 'GET', url: c.url(`api/v1/auth/check/${encodeURIComponent(ctx.user)}`) }, { signal }), 'Checking the credentials failed').text);
  if (st === 'unknown') throw new HostError('auth', 'The credentials are waiting for approval. Approve access in the dialog on the printer’s screen, then test again.');
  if (st !== 'authorized') throw new HostError('auth', 'Invalid authentication credentials.');
  const v = await c.send({ method: 'GET', url: c.url('api/v1/auth/verify') }, { signal });
  if (v.status === 403 || message(v.text) !== 'ok') throw new HostError('auth', 'Invalid authentication credentials.');
}

export const ultimaker: PrintHostDriver = {
  async test(ctx, env, signal) {
    const c = client(ctx, env);
    const r = expectOk(await c.send({ method: 'GET', url: c.url('api/v1/system/variant') }, { signal }), 'The UltiMaker didn’t accept the request');
    const body = r.text.trim();
    if (!(body.startsWith('"Ultimaker 3') || body === '"Ultimaker S5"')) throw new HostError('protocol', `This doesn’t look like an UltiMaker 3 / S5 (system variant: ${body.slice(0, 60) || 'empty'}).`);
    await checkAuth(ctx, env, signal);
    return { message: 'Connection to UltiMaker works correctly.', detail: body.replace(/"/g, '') };
  },
  async upload(ctx, job, env, cb = {}) {
    if (!job.print) throw new HostError('unsupported', 'UltiMaker printers start every job they receive: use Upload & Print.');
    const c = um(ctx, env);
    cb.onStatus?.('Connecting');
    expectOk(await c.send({ method: 'GET', url: c.url('api/v1/printer/status') }, { signal: cb.signal }), 'The UltiMaker isn’t reachable');
    const file = new Blob([griffinCompatible(await job.file.text())], { type: 'text/x-gcode' });
    cb.onStatus?.('Uploading');
    const r = expectOk(await c.send({ method: 'POST', url: c.url('api/v1/print_job'), body: formFile({ jobname: job.filename }, 'file', file, job.filename) },
      { onProgress: cb.onProgress, signal: cb.signal }), 'Upload failed');
    const err = tryJson<{ err?: number }>(r.text)?.err ?? 0;
    if (err) throw new HostError('protocol', 'Unknown error occurred', r.text);
    return { message: 'Uploaded to the UltiMaker and started printing.', printed: true, path: job.filename };
  },
};
