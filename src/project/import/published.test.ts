// Published 3MFs (Orca 2.5 Publish): metadata reading and the material pass's slot plan
// (PresetBundle::load_config_file_config, published mode), and Orca's INI reader.
import { describe, expect, it } from 'vitest';
import { readOrcaIni } from './ini';
import {
  candidateScore, isPublishedFlag, normalizeFilamentType, planPublishedSlots, publishKeyIndex, publishMaterialBaseName, readPublished,
  relocateMixedCells, resolvePublishedExtruderSlot, type PublishedMaterial,
} from './published';

const mat = (slot: number, keys: string[], extra: Partial<PublishedMaterial> = {}): PublishedMaterial => ({
  slot, keys, full: false, fullKeys: [], publishType: false, type: '', publishColor: false, color: '',
  material: { filamentType: '', filamentVendor: '', filamentId: '', settingId: '', name: '' }, ...extra,
});
const MIX = ['filament_is_mixed', 'filament_mixed_components'];

describe('readOrcaIni (boost read_ini rules)', () => {
  it('reads trimmed key = value lines, skips comments and sections', () => {
    expect(readOrcaIni('# generated by OrcaSlicer\n; c\n  a = 1 \r\nb=x = y\n[sec]\nc = 3\n')).toEqual({ a: '1', b: 'x = y' });
  });
  it('a line without "=", an empty key or a duplicate key makes the text unreadable', () => {
    expect(readOrcaIni('a = 1\nnot a pair\n')).toBeNull();
    expect(readOrcaIni(' = 1\n')).toBeNull();
    expect(readOrcaIni('a = 1\na = 2\n')).toBeNull();
  });
});

describe('published metadata', () => {
  const meta = (m: Record<string, string>) => (k: string) => m[k];
  it('only orca_published == "1" is a published file', () => {
    expect(isPublishedFlag('1')).toBe(true);
    for (const v of ['true', '0', ' 1', undefined]) expect(isPublishedFlag(v)).toBe(false);
    expect(readPublished(meta({ orca_published: 'true', orca_published_keys: '["a"]' }), [])).toBeNull();
  });

  it('reads material identity, type requirement, full keys, layouts; a malformed entry is skipped on its own', () => {
    const w: string[] = [];
    const p = readPublished(meta({
      orca_published: '1',
      orca_published_keys: '["wall_loops", 3, "retraction_length#1"]',
      orca_published_material_keys: JSON.stringify([
        'junk',
        { slot: 0, keys: ['filament_type'], publish_type: true, type: 'PETG', publish_color: true, color: '#112233',
          material: { filament_type: 'PETG', filament_vendor: 'Generic', filament_id: 'GFG99', setting_id: 'GFSG99', name: 'Generic PETG @System' } },
        { slot: 1, keys: [], full: true, full_keys: ['filament_max_volumetric_speed', 7] },
        { keys: ['filament_type'] },
      ]),
      orca_published_extruder_layout: JSON.stringify({ extruder_ids: [1, 2], variants: ['Direct Drive Standard', 'Direct Drive High Flow'], print_extruder_ids: [1], print_variants: ['Direct Drive Standard'] }),
      orca_published_config: '; payload\nwall_loops = 3\nretraction_length = 0.8,1.2\n',
    }), w);
    expect(w).toEqual([]);
    expect(p!.keys).toEqual(['wall_loops', 'retraction_length#1']);
    expect(p!.materials).toHaveLength(3);
    expect(p!.materials[0]).toMatchObject({ slot: 0, publishType: true, type: 'PETG', publishColor: true, color: '#112233',
      material: { filamentType: 'PETG', filamentVendor: 'Generic', filamentId: 'GFG99', settingId: 'GFSG99', name: 'Generic PETG @System' } });
    expect(p!.materials[1]).toMatchObject({ slot: 1, full: true, keys: [], fullKeys: ['filament_max_volumetric_speed'] });
    expect(p!.materials[2].slot).toBe(-1);
    expect(p!.printerLayout).toEqual({ extruderIds: [1, 2], variants: ['Direct Drive Standard', 'Direct Drive High Flow'] });
    expect(p!.printLayout).toEqual({ extruderIds: [1], variants: ['Direct Drive Standard'] });
    expect(p!.config).toEqual({ wall_loops: '3', retraction_length: '0.8,1.2' });
  });

  it('a malformed layout or payload is ignored with the rest still read', () => {
    const w: string[] = [];
    const p = readPublished(meta({ orca_published: '1', orca_published_extruder_layout: '{"variants":["x"]}', orca_published_config: 'a = 1\na = 2' }), w);
    expect(p).toMatchObject({ keys: [], materials: [], config: {}, printerLayout: null, printLayout: null });
    expect(w).toEqual(['The published settings couldn’t be read.']);
  });
});

describe('publish helpers', () => {
  it('key index, type family, base name', () => {
    expect([publishKeyIndex('a#2'), publishKeyIndex('a'), publishKeyIndex('a#'), publishKeyIndex('a#1x')]).toEqual([2, -1, -1, -1]);
    expect([normalizeFilamentType('PLA High Speed'), normalizeFilamentType('PA-CF'), normalizeFilamentType('Weird Stuff')]).toEqual(['PLA', 'PA-CF', 'Weird Stuff']);
    expect(publishMaterialBaseName('Generic PLA @System')).toBe('Generic PLA');
  });

  it('candidate score tiers', () => {
    const e = mat(0, [], { type: 'PLA', material: { filamentType: 'PLA', filamentVendor: 'Bambu', filamentId: 'GFA00', settingId: 'S1', name: 'Bambu PLA Basic @BBL X1C' } });
    expect(candidateScore({ name: 'Bambu PLA Basic @BBL X1C' }, e, '')).toBe(5);
    expect(candidateScore({ name: 'Renamed' }, e, 'Renamed')).toBe(5);
    expect(candidateScore({ name: 'Bambu PLA Basic' }, e, '')).toBe(4);
    expect(candidateScore({ name: 'x', alias: 'Bambu PLA Basic' }, e, '')).toBe(4);
    expect(candidateScore({ name: 'x', settingId: 'S1' }, e, '')).toBe(3);
    expect(candidateScore({ name: 'x', filamentId: 'GFA00' }, e, '')).toBe(2);
    expect(candidateScore({ name: 'x', filamentType: 'PLA High Speed', filamentVendor: 'Bambu' }, e, '')).toBe(1);
    expect(candidateScore({ name: 'x', filamentType: 'PLA', filamentVendor: 'Generic' }, e, '')).toBe(0);
    expect(candidateScore({ name: 'x', filamentType: 'PETG' }, e, '')).toBe(-1);
  });

  it('per-extruder keys by extruder identity (resolve_published_extruder_slot)', () => {
    const layout = { extruderIds: [1, 2], variants: ['Direct Drive Standard', 'Direct Drive High Flow'] };
    const receiver = { nozzleCount: 2, extruderTypes: ['Direct Drive', 'Direct Drive'], volumeTypes: ['Standard', 'High Flow'] };
    const target = { ids: [1, 1, 2, 2], variants: ['Direct Drive Standard', 'Direct Drive High Flow', 'Direct Drive Standard', 'Direct Drive High Flow'] };
    expect(resolvePublishedExtruderSlot(layout, 0, receiver, target)).toBe(0);
    expect(resolvePublishedExtruderSlot(layout, 1, receiver, target)).toBe(3);
    // The receiver's extruder 2 runs Standard now: the author's High Flow value doesn't apply.
    expect(resolvePublishedExtruderSlot(layout, 1, { ...receiver, volumeTypes: ['Standard', 'Standard'] }, target)).toBe(-1);
    expect(resolvePublishedExtruderSlot(layout, 1, { ...receiver, nozzleCount: 1 }, target)).toBe(-1);
  });
});

describe('material slot plan', () => {
  it('grows only as far as the highest published slot, capped by the file’s filament count', () => {
    const plan = planPublishedSlots([mat(3, ['filament_type'])], { physical: 1, mixed: 0, capacity: 4 }, 2);
    expect(plan.targetSlots).toBe(2);
    expect(planPublishedSlots([mat(3, ['filament_type'])], { physical: 1, mixed: 0, capacity: 4 }, 4).targetSlots).toBe(4);
    // Never shrinks.
    expect(planPublishedSlots([mat(0, ['filament_type'])], { physical: 3, mixed: 0, capacity: 4 }, 1).targetSlots).toBe(3);
  });

  it('a payload mixed filament authored on a real slot moves to the tail; the model follows', () => {
    const plan = planPublishedSlots([mat(1, MIX)], { physical: 2, mixed: 0, capacity: 4 }, 3);
    expect(plan.entries[0]).toMatchObject({ slot: 2, authoredSlot: 1 });
    expect([...plan.relocations]).toEqual([[1, 2]]);
    expect(plan.payloadMoves).toEqual([[1, 2]]);
    expect(plan.targetSlots).toBe(3);
    expect(plan.notes).toEqual(['slot 1 -> slot 2: mixed filament']);
  });

  it('a payload mix over a receiver mix keeps its place (like for like)', () => {
    const plan = planPublishedSlots([mat(2, MIX)], { physical: 2, mixed: 1, capacity: 4 }, 3);
    expect(plan.entries[0].slot).toBe(2);
    expect(plan.relocations.size).toBe(0);
  });

  it('receiver mixes inside the incoming physical region are displaced to the tail', () => {
    // Receiver: 2 real + mixes at 2, 3. The author published a real filament at slot 2.
    const plan = planPublishedSlots([mat(2, ['filament_type'])], { physical: 2, mixed: 2, capacity: 4 }, 3);
    expect(plan.receiverMoves).toEqual([[2, 4]]);
    expect([...plan.relocations]).toEqual([[2, 4]]);
    expect(plan.targetSlots).toBe(5);
    expect(plan.entries[0].slot).toBe(2);
  });

  it('surplus materials past the printer capacity become empty mixed placeholders; one nozzle drops them', () => {
    const plan = planPublishedSlots([mat(0, ['filament_type']), mat(3, ['filament_type'])], { physical: 2, mixed: 0, capacity: 2 }, 4);
    expect(plan.entries[1]).toMatchObject({ slot: 2, authoredSlot: 3, placeholder: true });
    expect([...plan.relocations]).toEqual([[3, 2]]);
    expect(plan.notes).toEqual(["slot 3 -> slot 2: unassigned mixed filament (the printer's filament limit is 2)"]);
    const single = planPublishedSlots([mat(1, ['filament_type'])], { physical: 1, mixed: 0, capacity: 1 }, 2);
    expect(single.entries).toEqual([]);
    expect(single.skipped).toEqual(["material: (the printer's filament limit is 1)"]);
  });

  it('unpublished slots grown past the capacity become placeholders; the slot limit is reported', () => {
    const plan = planPublishedSlots([mat(4, MIX)], { physical: 2, mixed: 0, capacity: 2 }, 5);
    expect(plan.entries[0].slot).toBe(4);
    expect(plan.targetSlots).toBe(5);
    expect(plan.gapSlots).toEqual([2, 3]);
    const full = planPublishedSlots([mat(32, MIX, { material: { filamentType: '', filamentVendor: '', filamentId: 'GFX', settingId: '', name: '' } })], { physical: 2, mixed: 0, capacity: 2 }, 40);
    expect(full.skipped).toEqual(['material:GFX (mixed filament definition: filament slot limit reached)']);
  });

  it('mixed cells move from a snapshot (adjacent relocations don’t overwrite each other)', () => {
    expect(relocateMixedCells(['a', 'b', 'c'], [[1, 2], [2, 3]], '')).toEqual(['a', 'b', 'b', 'c']);
  });
});
