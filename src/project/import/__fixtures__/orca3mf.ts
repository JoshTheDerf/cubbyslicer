// Builds an OrcaSlicer-style project 3MF (bbs_3mf.cpp layout) for tests:
// two plates, an object with a model part + modifier (painted, with settings),
// a second object with two instances on different plates, project settings and
// plate 2's sliced G-code.
import { strToU8, zipSync } from 'fflate';

function boxMesh(id: number, x0: number, y0: number, z0: number, s: number, paintFirst = false): string {
  const v = [[0, 0, 0], [s, 0, 0], [s, s, 0], [0, s, 0], [0, 0, s], [s, 0, s], [s, s, s], [0, s, s]].map(([x, y, z]) => [x + x0, y + y0, z + z0]);
  const f = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]];
  return `<object id="${id}" type="model"><mesh><vertices>${v.map((p) => `<vertex x="${p[0]}" y="${p[1]}" z="${p[2]}"/>`).join('')}</vertices>`
    + `<triangles>${f.map((t, i) => `<triangle v1="${t[0]}" v2="${t[1]}" v3="${t[2]}"${paintFirst && i === 2 ? ' paint_color="8"' : ''}/>`).join('')}</triangles></mesh></object>`;
}

export function orcaProject3mf(): Uint8Array {
  const P = 'http://schemas.microsoft.com/3dmanufacturing/production/2015/06';
  const objects = `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources>
${boxMesh(1, -10, -10, 0, 20, true)}
${boxMesh(2, -5, -5, 5, 10)}
${boxMesh(3, -8, -8, 0, 16)}
</resources></model>`;
  const root = `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" xmlns:p="${P}" requiredextensions="p"><resources>
<object id="4" type="model"><components>
  <component p:path="/3D/Objects/object_1.model" objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>
  <component p:path="/3D/Objects/object_1.model" objectid="2" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>
</components></object>
<object id="5" type="model"><components>
  <component p:path="/3D/Objects/object_1.model" objectid="3" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>
</components></object>
</resources><build>
<item objectid="4" transform="1 0 0 0 1 0 0 0 1 128 128 0" printable="1"/>
<item objectid="5" transform="1 0 0 0 1 0 0 0 1 60 60 0" printable="1"/>
<item objectid="5" transform="1 0 0 0 1 0 0 0 1 367.2 128 0" printable="1"/>
</build></model>`;
  const settings = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <object id="4">
    <metadata key="name" value="Box with modifier"/>
    <metadata key="extruder" value="1"/>
    <metadata key="wall_loops" value="4"/>
    <part id="1" subtype="normal_part"><metadata key="name" value="Box"/><metadata key="extruder" value="2"/></part>
    <part id="2" subtype="modifier_part"><metadata key="name" value="Dense core"/><metadata key="sparse_infill_density" value="80%"/></part>
  </object>
  <object id="5">
    <metadata key="name" value="Small box"/>
    <part id="3" subtype="normal_part"><metadata key="name" value="Small box"/></part>
  </object>
  <plate>
    <metadata key="plater_id" value="1"/><metadata key="plater_name" value="Main"/><metadata key="locked" value="false"/>
    <model_instance><metadata key="object_id" value="4"/><metadata key="instance_id" value="0"/></model_instance>
    <model_instance><metadata key="object_id" value="5"/><metadata key="instance_id" value="0"/></model_instance>
  </plate>
  <plate>
    <metadata key="plater_id" value="2"/><metadata key="plater_name" value="Spares"/><metadata key="locked" value="true"/>
    <metadata key="gcode_file" value="Metadata/plate_2.gcode"/>
    <model_instance><metadata key="object_id" value="5"/><metadata key="instance_id" value="1"/></model_instance>
  </plate>
</config>`;
  const project = {
    printable_area: ['0x0', '256x0', '256x256', '0x256'],
    printer_settings_id: 'Bambu Lab X1 Carbon 0.4 nozzle',
    print_settings_id: '0.20mm Standard @BBL X1C',
    filament_settings_id: ['Bambu PLA Basic @BBL X1C', 'Bambu PLA Basic @BBL X1C'],
    filament_colour: ['#FFFFFF', '#E4572E'],
    sparse_infill_density: '25%',
    wall_loops: '3',
    different_settings_to_system: ['sparse_infill_density', '', '', ''],
  };
  return zipSync({
    '[Content_Types].xml': strToU8('<?xml version="1.0"?><Types/>'),
    '_rels/.rels': strToU8('<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>'),
    '3D/3dmodel.model': strToU8(root),
    '3D/Objects/object_1.model': strToU8(objects),
    'Metadata/model_settings.config': strToU8(settings),
    'Metadata/project_settings.config': strToU8(JSON.stringify(project)),
    'Metadata/plate_2.gcode': strToU8('; generated by OrcaSlicer\nG28\nG1 X10 Y10 Z0.2 F3000\nG1 X20 Y10 E1\n'),
  });
}

/** An Orca "export plate sliced file" 3MF: G-code only, no models. */
export function orcaSlicedOnly3mf(): Uint8Array {
  return zipSync({
    '[Content_Types].xml': strToU8('<?xml version="1.0"?><Types/>'),
    '3D/3dmodel.model': strToU8('<?xml version="1.0"?><model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources/><build/></model>'),
    'Metadata/model_settings.config': strToU8('<?xml version="1.0"?><config><plate><metadata key="plater_id" value="1"/><metadata key="gcode_file" value="Metadata/plate_1.gcode"/></plate></config>'),
    'Metadata/plate_1.gcode': strToU8('; generated by OrcaSlicer\nG28\n'),
  });
}
