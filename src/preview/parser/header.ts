/**
 * Header / footer / config-block comments: `key = value` and `key: value`
 * lines slicers write around the toolpaths (time, layer count, filament
 * usage) and the `; CONFIG_BLOCK_START … END` dump of the slicing config.
 */
import { numList, parseDuration } from './bytes';
import type { GcodeHeaderInfo } from './types';

/**
 * Config-block keys kept in `header.config`: what the preview needs to draw a
 * file without the project (filament colours incl. Orca 2.5 translucent /
 * multi-colour, mixed filament slots, belt geometry).
 */
export const HEADER_CONFIG_KEYS: ReadonlySet<string> = new Set([
  'filament_colour', 'filament_multi_colour', 'filament_colour_type', 'extruder_colour', 'filament_type',
  'filament_is_mixed', 'filament_mixed_components',
  'belt_printer', 'belt_slice_rotation', 'belt_slice_rotation_angle', 'belt_frame_tilt_angle', 'belt_frame_tilt_decouple',
  'gcode_remap_x', 'gcode_remap_y', 'gcode_remap_z', 'printable_area', 'printable_height',
  'printer_model', 'nozzle_diameter',
]);

/**
 * A config-block value as the engine hands it to the app: vectors as arrays.
 * Orca serializes string vectors `;`-separated with `"…"` quoting where needed
 * (`ConfigOptionStrings::serialize`) and number / bool vectors `,`-separated.
 */
export function deserializeValue(v: string): string | string[] {
  if (v.includes('"')) {
    const out: string[] = [];
    const re = /"((?:[^"\\]|\\.)*)"|([^;]*)/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(v)) && m.index < v.length) {
      out.push(m[1] !== undefined ? m[1].replace(/\\(.)/g, '$1') : m[2].trim());
      re.lastIndex = m.index + m[0].length + 1; // skip the ';'
    }
    return out;
  }
  if (v.includes(';')) return v.split(';').map((x) => x.trim());
  if (v.includes(',')) return v.split(',').map((x) => x.trim());
  return v;
}

export function emptyHeader(): GcodeHeaderInfo {
  return {
    generator: null, printTimeSec: null, layerCount: null, maxZ: null,
    filamentMm: null, filamentG: null, filamentCm3: null, filamentCost: null, filamentDiameter: null,
    beltTiltAngle: null, config: {},
  };
}

/**
 * Read one header comment into `H`. `inConfig`: inside the config block, where
 * Orca lists every key (so `belt_slice_rotation_angle` there doesn't mean belt).
 * Returns the filament diameter the first time the file states one.
 */
export function readHeaderComment(s: string, H: GcodeHeaderInfo, inConfig: boolean): number | null {
  const kv = s.match(/^([^=:]+?)\s*[=:]\s*(.*)$/);
  if (!kv) return null;
  const key = kv[1].toLowerCase(), val = kv[2];
  if (inConfig) {
    if (HEADER_CONFIG_KEYS.has(key)) H.config[key] = deserializeValue(val.trim());
  } else if (key === 'belt_slice_rotation_angle') {
    const v = Math.abs(Number(val));
    if (Number.isFinite(v)) H.beltTiltAngle = v;
    return null;
  }
  if (key.startsWith('generated by')) { H.generator = s.slice(12).trim(); return null; }
  if (key.startsWith('estimated printing time (normal mode)') || key === 'estimated printing time') {
    const t = parseDuration(val); if (t === t) H.printTimeSec = t; return null;
  }
  if (key === 'model printing time') {
    const m = s.match(/total estimated time:\s*([^;]+)/i);
    if (m) { const t = parseDuration(m[1]); if (t === t) H.printTimeSec = t; }
    return null;
  }
  if (key === 'total estimated time') { const t = parseDuration(val); if (t === t) H.printTimeSec = t; return null; }
  if (key === 'total layers count' || key === 'total layer number' || key === 'total_layer_count') {
    const v = Number(val); if (Number.isFinite(v)) H.layerCount = v; return null;
  }
  if (key === 'max_z_height') { const v = Number(val); if (Number.isFinite(v)) H.maxZ = v; return null; }
  if (key === 'filament used [mm]') { H.filamentMm = numList(val); return null; }
  if (key === 'filament used [g]') { H.filamentG = numList(val); return null; }
  if (key === 'filament used [cm3]') { H.filamentCm3 = numList(val); return null; }
  if (key === 'filament cost') { H.filamentCost = numList(val); return null; }
  if (key === 'filament_diameter' && H.filamentDiameter === null) {
    const v = numList(val)[0];
    if (v > 0) { H.filamentDiameter = v; return v; }
  }
  return null;
}
